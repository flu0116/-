package curriculum_A;

public class Qes11 {

	public static void main(String[] args) {
		
		int age = 24; // 年齢
		double height = 168.5; // 身長
		double weight = 64.2; // 体重
		
		
		String newAge = String.valueOf(age); // 年齢をString型に変換
		String newHeight = String.valueOf(height); // 身長をString型に変換
		String newWeight = String.valueOf(weight); // 体重をString型に変換
		
		System.out.println(newAge + newHeight + newWeight);
	

	}

}
