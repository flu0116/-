package curriculum_A;

public class Qes2 {

	public static void main(String[] args) {
		
		byte b = 0; // バイト型を宣言し、初期化する
		 
		short s = 0; // 短整数型を宣言し、初期化する
		 
		int i = 0; // 整数型を宣言し、初期化する
		 
		long l = 0L; // 長整数型を宣言し、初期化する
		 
		float f = 0.0f; // 単精度浮動小数点数型を宣言し、初期化する
		
		double d = 0.0d; // 倍精度浮動小数点数型を宣言し、初期化する
		
		char c = 'a'; // 文字型を宣言し、初期化する
		
		String str = "b"; // 文字列型を宣言し、初期化する
		
		boolean bool = false; // ブーリアン型を宣言し、初期化する

	}

}
